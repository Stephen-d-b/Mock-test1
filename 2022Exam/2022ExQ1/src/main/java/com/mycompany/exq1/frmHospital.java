    // Q.1.1 - SAVE Button
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // Check if we have reached the maximum limit of 5 inspections
        if (inspectionCount >= 5) {
            JOptionPane.showMessageDialog(this, "Maximum inspection count reached!");
            return; // Stop the method here so it doesn't try to save
        }

        // If we haven't reached 5, save the input to the arrays at the current index
        hospitalNames[inspectionCount] = txtName.getText();
        hospitalLocations[inspectionCount] = txtLocation.getText();
        yearsSince[inspectionCount] = cmbYears.getSelectedItem().toString();
        
        // Increment the counter so the next save goes to the next slot in the array
        inspectionCount++; 
        
        JOptionPane.showMessageDialog(this, "Inspection saved successfully!");
    }//GEN-LAST:event_btnSaveActionPerformed

    // Q.1.1 - PRINT Button
    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        // Clear the text area first so we don't print duplicates
        txtInfo.setText(""); 
        
        // Loop through the arrays ONLY up to the number of saved inspections.
        for (int i = 0; i < inspectionCount; i++) {
            // Build the output string matching the sample screenshot
            String output = "Hospital Name: " + hospitalNames[i] + "\n" +
                            "Hospital Location: " + hospitalLocations[i] + "\n" +
                            "Years Since Inspection: " + yearsSince[i] + "\n" +
                            "********************************************\n";
            
            // Append the formatted text to the text area (txtInfo)
            txtInfo.append(output);
        }
    }//GEN-LAST:event_btnPrintActionPerformed

