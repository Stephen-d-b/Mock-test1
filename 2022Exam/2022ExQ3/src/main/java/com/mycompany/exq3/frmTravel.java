    // Q.3.1, Q.3.2, Q.3.5
    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // 1. Capture the currently selected items from the combo boxes
        String start = cmbStart.getSelectedItem().toString();
        String end = cmbEnd.getSelectedItem().toString();
        String travelBy = cmbTravelBy.getSelectedItem().toString();

        // Q.3.5 - Validate that the start and end locations are not the same
        if (start.equals(end)) {
            // Show the exact error message from the exam screenshot
            JOptionPane.showMessageDialog(this, "Destinations cannot be the same!!!");
            return; // Stop the method here so it doesn't save to the file
        }

        // Q.3.2 - Save the travel information to the sequential file
        // We use 'true' as the second parameter in FileWriter to APPEND to the file
        // instead of overwriting the whole thing every time we click submit.
        try (FileWriter fw = new FileWriter("travel.txt", true);
             PrintWriter pw = new PrintWriter(fw)) {
            
            // Write to the file separated by commas (CSV format)
            // Example: Cape Town,Durban,Train
            pw.println(start + "," + end + "," + travelBy);
            
        } catch (IOException e) {
            // If there is a file error (e.g., file is locked), show a popup
            JOptionPane.showMessageDialog(this, "Error saving file: " + e.getMessage());
        }

        // Q.3.3 - Reload the data from the file into the Text Area so the new entry appears
        loadDataFromFile();
    }//GEN-LAST:event_btnSubmitActionPerformed

