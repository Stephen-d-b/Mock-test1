    // Q.3.3 - Reads the travel.txt file and prints it into the text area
    private void loadDataFromFile() {
        // Clear the text area first so we don't get duplicate text every time we load
        txtArea.setText(""); 
        
        // Try-with-resources automatically closes the scanner when done
        try (Scanner scanner = new Scanner(new File("travel.txt"))) {
            
            // Loop through the file line by line
            while (scanner.hasNextLine()) {
                String line = scanner.nextLine();
                
                // Split the line by the comma we wrote earlier
                String[] parts = line.split(","); 
                
                // Make sure the line actually had 3 parts before trying to print it
                if (parts.length == 3) {
                    // Format the text exactly like the sample screenshot
                    String display = "Destination 1: " + parts[0] + "\n" +
                                     "Destination 2: " + parts[1] + "\n" +
                                     "Travel By: " + parts[2] + "\n" +
                                     "***********************************\n\n";
                    
                    // Append it to the text area
                    txtArea.append(display);
                }
            }
        } catch (java.io.FileNotFoundException e) {
            // If the file doesn't exist yet (e.g., the very first time running the app),
            // we just ignore the error. It will be created when they click Submit.
        }
    }
    
    
