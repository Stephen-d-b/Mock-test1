    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        
        String strCustomer = this.txtCustomerInput.getText();
        int intTour = this.cbmTour.getSelectedIndex();
        double dblCost = getCost(intTour);
        
        if(this.optYes.isSelected())
        {
            dblCost -= dblCost * 0.10;
        }
        
        this.txaBooking.setText("CUSTOMER: " + strCustomer + "\n" + "TOUR: " + this.cbmTour.getSelectedItem().toString() + "\n" + "TOTAL: R" + dblCost);
// TODO add your handling code here:
    }//GEN-LAST:event_btnProcessActionPerformed

    private double getCost(int intTour)
    {
        double[] dblCost = {3000, 1800, 3500};
        return dblCost[intTour];
    }
    
    
