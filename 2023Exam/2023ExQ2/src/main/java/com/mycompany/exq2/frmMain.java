    // Q.2.4 - Process Report
    // Triggered when the user clicks Tools -> Process Report
    private void mnuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuProcessActionPerformed
        try {
            // 1. Capture all text input from the GUI components
            String location = cmbLocation.getSelectedItem().toString();
            String name = txtName.getText();
            String priceStr = txtPrice.getText();
            String commStr = txtCommission.getText();

            // 2. Convert the String inputs to doubles for mathematical calculations
            double price = Double.parseDouble(priceStr);
            double commPct = Double.parseDouble(commStr);

            // 3. Create a Data object to hold the captured values
            Data data = new Data(location, name, price, commPct);
            
            // 4. Pass the Data object to the validation method in the logic class
            if (!logic.ValidateData(data)) {
                // If validation fails (e.g., empty name or 0 price), show an error and stop.
                JOptionPane.showMessageDialog(this, "Invalid input. Please check fields.");
                return; // Exits the method early
            }

            // 5. If validation passes, calculate the commission using the interface method
            double calculatedCommission = logic.CalculateCommission(priceStr, commStr);

            // 6. Build the final report string using String.format
            // %s = String, %.1f = float with 1 decimal, %% = literal percentage sign
            String report = String.format(
                "AGENT LOCATION: %s\nAGENT NAME: %s\nPROPERTY PRICE: R %.1f\nCOMMISSION PERCENTAGE: %.1f%%\nCALCULATED COMMISSION: R %.1f",
                location, name, price, commPct, calculatedCommission
            );
            
            // 7. Display the formatted report in the text area
            txtReport.setText(report);

        } catch (NumberFormatException e) {
            // This catch block handles errors if the user types letters instead of numbers
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for price and commission.");
        }
    }//GEN-LAST:event_mnuProcessActionPerformed

    // Q.2.5 - Save Report to text file
    // Triggered when the user clicks Tools -> Save Report
    private void mnuSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuSaveActionPerformed
        // try-with-resources automatically closes the file writer when done
        try (FileWriter writer = new FileWriter("report.txt")) {
            // Write the header and formatting lines
            writer.write("ESTATE AGENT REPORT\n");
            writer.write("**************************************************\n");
            
            // Write exactly what is currently showing in the GUI text area
            writer.write(txtReport.getText() + "\n");
            
            // Write the bottom formatting line
            writer.write("**************************************************\n");
            
            // Show a success message to the user
            JOptionPane.showMessageDialog(this, "Report saved to report.txt successfully.");
            
        } catch (IOException ex) {
            // Handle file errors (e.g., if the file is open in another program)
            JOptionPane.showMessageDialog(this, "Error saving file: " + ex.getMessage());
        }
    }//GEN-LAST:event_mnuSaveActionPerformed

