    private void btnSaveDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveDataActionPerformed
        try {
            // Create the file
            FileWriter fw = new FileWriter("data.txt");
            
            // Write the header
            fw.write("DATA LOG\n");
            fw.write("***************************\n");
            
            // Loop through the JList and write each line to the file
            for (int i = 0; i < lstDisplay.getModel().getSize(); i++) {
                fw.write(lstDisplay.getModel().getElementAt(i) + "\n");
            }
            
            fw.write("***************************\n");
            fw.close();
            
            JOptionPane.showMessageDialog(this, "Data successfully saved to data.txt");
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving file.");
        }
    }//GEN-LAST:event_btnSaveDataActionPerformed

    private void btnLoadDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadDataActionPerformed
        int total = ps.GetTotalSales();
        double avg = ps.GetAverageSales();
        int over = ps.GetSalesOverLimit();
        int under = ps.GetSalesUnderLimit();
        int years = ps.GetProductsProcessed();

        // Create an array of Strings to feed into the JList
        String[] reportData = {
            "Total Sales: " + total,
            "Average Sales: " + Math.round(avg), 
            "Sales over limit: " + over,
            "Sales under limit: " + under
        };

        // Display the data
        lstDisplay.setListData(reportData);
        yrsProcessed.setText("Years Processed: " + years);
    }//GEN-LAST:event_btnLoadDataActionPerformed

