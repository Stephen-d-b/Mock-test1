    private void mnuProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuProcessActionPerformed
        try {
            // 1. Capture input
            String movie = cmbMovie.getSelectedItem().toString();
            int numTickets = Integer.parseInt(nrTickets.getText());
            double price = Double.parseDouble(TicketPrice.getText());

            // 2. Wrap in Data object and Validate
            MovieTicketData data = new MovieTicketData(movie, numTickets, price);
            
            if (!logic.ValidateData(data)) {
                JOptionPane.showMessageDialog(this, "Invalid input! Tickets and price must be > 0.");
                return; // Stop processing
            }

            // 3. Calculate total with VAT
            double totalPrice = logic.CalculateTotalTicketPrice(numTickets, price);

            // 4. Build and display the report
            String report = String.format(
                "MOVIE NAME: %s\nMOVIE TICKET PRICE: R %.1f\nNUMBER OF TICKETS: %d\nTOTAL TICKET PRICE: R %.1f",
                movie, price, numTickets, totalPrice
            );
            txtReport.setText(report);

            // 5. Save to file (report.txt)
            try (FileWriter writer = new FileWriter("report.txt")) {
                writer.write("MOVIE TICKET REPORT\n");
                writer.write("************************\n");
                writer.write(report + "\n");
                writer.write("************************\n");
            } catch (IOException ex) {
                JOptionPane.showMessageDialog(this, "Error saving file: " + ex.getMessage());
            }

        } catch (NumberFormatException ex) {
            // Catch error if user types letters instead of numbers
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for tickets and price.");
        }
    }//GEN-LAST:event_mnuProcessActionPerformed

